/**
 * Copies the owner's Firefly keyboard sets from the Audio Lab into
 * static/sounds/keys/. Audio never goes into Git (owner rule): only the small
 * JSON manifests are tracked. installed.json (ignored) is written last and
 * lists the sets copied: the game lists a set only when it is there, so a
 * clone or a build without this sync shows "sound files not installed".
 *
 * Each set's own keys-manifest.json names its samples (catalogue-2, owner
 * 30/10: 70-80 keys and 8 spaces per set); a set without one falls back to
 * the first layout, key-01..10 and space-01..03.
 *
 * The root catalogue is written as 2-space JSON (the repo's oxfmt layout),
 * whatever indent the Audio Lab uses: same fields and values, so a null
 * score or an owner's pick (ownerPick) stays as listed, and a Lab file that
 * differs only in layout is current.
 *
 * keys.sha256 (tracked) records the audio the code expects: one
 * "<sha256>  <set>/<file>" line per OGG, sorted by path, the format
 * `shasum -a 256 -c keys.sha256` reads in that folder. A sync rewrites it,
 * so new takes from the Audio Lab show up as a Git change.
 *
 * Usage (in frontend): pnpm sync-keys [--check]
 *   KEYS_FIREFLY_DIR overrides the source (default ~/AudioLab/review/staging/keys-firefly).
 *   --check copies nothing and exits 1 when a local OGG is missing or not the
 *   version keys.sha256 records, or, when the Audio Lab is on this machine,
 *   when its takes or JSON differ from what Git holds. Without the Audio Lab
 *   it checks the local audio against keys.sha256 only.
 */
import { createHash } from "node:crypto";
import {
  copyFileSync,
  existsSync,
  mkdirSync,
  readFileSync,
  writeFileSync,
} from "node:fs";
import { homedir } from "node:os";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const ID = /^[a-z0-9][a-z0-9-]{0,31}$/;
/** What the kit's keyboardFiles() reads: key-NN or key-NNN, OGG only (no WAV in the game). */
const SAMPLE = /^(key|space)-(\d{2,3})\.ogg$/;
const number2 = (n: number): string => String(n).padStart(2, "0");
const LEGACY_FILES = [
  ...Array.from({ length: 10 }, (_, i) => `key-${number2(i + 1)}.ogg`),
  ...Array.from({ length: 3 }, (_, i) => `space-${number2(i + 1)}.ogg`),
];
const PREVIEW = "preview.ogg";
const SUMS = "keys.sha256";
/** A keys.sha256 line: a set's sample or preview, never a path outside the folder. */
const SUM_LINE =
  /^([0-9a-f]{64}) {2}([a-z0-9][a-z0-9-]{0,31}\/(?:(?:key|space)-\d{2,3}|preview)\.ogg)$/;
const DEFAULT_LICENCE =
  "Adobe Firefly Generate Sound Effects, generated by the project owner (Adobe model)";

const here = dirname(fileURLToPath(import.meta.url));
const dest = resolve(here, "../static/sounds/keys");
const source = resolve(
  process.env["KEYS_FIREFLY_DIR"] ??
    join(homedir(), "AudioLab/review/staging/keys-firefly"),
);
const check = process.argv.includes("--check");

/** A file to write: a copy of `from` (its sha256 in `sha`) or `text`. */
type Item = {
  from: string | null;
  sha: string | null;
  to: string;
  text: string | null;
};
/** What the Audio Lab holds: the files to write, the set ids, sha256 by OGG path. */
type Lab = { plan: Item[]; sets: string[]; sums: Map<string, string> };

function fail(message: string): never {
  console.error(`sync-keys: ${message}`);
  process.exit(2);
}

function sha(path: string): string {
  return createHash("sha256").update(readFileSync(path)).digest("hex");
}

function readJson(path: string): unknown {
  try {
    return JSON.parse(readFileSync(path, "utf8")) as unknown;
  } catch (error) {
    fail(`${path} is not JSON: ${(error as Error).message}`);
  }
}

function field(value: unknown, key: string): unknown {
  return value !== null && typeof value === "object"
    ? (value as Record<string, unknown>)[key]
    : undefined;
}

function text(value: unknown): string | null {
  return typeof value === "string" && value.trim() !== "" ? value : null;
}

/**
 * The OGG samples a set manifest names, keys then spaces by number. Entries
 * are file names or objects with `file` (and `set`); a name outside
 * key-NN/space-NN, a set that disagrees with the name, or a duplicate fails.
 */
function samples(id: string, manifest: unknown): string[] {
  const files = field(manifest, "files");
  if (!Array.isArray(files)) fail(`${id}: keys-manifest.json has no files`);
  const seen = new Set<string>();
  for (const entry of files as unknown[]) {
    const file = typeof entry === "string" ? entry : field(entry, "file");
    if (typeof file !== "string" || !SAMPLE.test(file)) {
      fail(`${id}: bad sample ${JSON.stringify(file)}`);
    }
    const set = typeof entry === "string" ? undefined : field(entry, "set");
    if (
      set !== undefined &&
      (typeof set !== "string" || !file.startsWith(`${set}-`))
    ) {
      fail(`${id}: ${file} is listed as ${JSON.stringify(set)}`);
    }
    if (seen.has(file)) fail(`${id}: ${file} listed twice`);
    seen.add(file);
  }
  const order = (file: string): number => {
    const [, set, n] = SAMPLE.exec(file) ?? [];
    return (set === "space" ? 1000 : 0) + Number(n);
  };
  const sorted = [...seen].sort((a, b) => order(a) - order(b));
  if (!sorted.some((f) => f.startsWith("key-"))) fail(`${id}: no key sample`);
  return sorted;
}

/** keys.sha256's text: one line per OGG, sorted by path. */
function sumsText(sums: ReadonlyMap<string, string>): string {
  return [...sums.keys()]
    .sort()
    .map((path) => `${sums.get(path)}  ${path}\n`)
    .join("");
}

/** The tracked keys.sha256, or null when there is none. */
function readSums(): Map<string, string> | null {
  const path = join(dest, SUMS);
  if (!existsSync(path)) return null;
  const sums = new Map<string, string>();
  for (const line of readFileSync(path, "utf8").split("\n")) {
    if (line === "") continue;
    const [, hash, file] = SUM_LINE.exec(line) ?? [];
    if (hash === undefined || file === undefined) {
      fail(`${SUMS}: bad line ${JSON.stringify(line)}`);
    }
    sums.set(file, hash);
  }
  return sums;
}

/** The Audio Lab's sets as files to write; null for --check on a machine without it. */
function readLab(): Lab | null {
  const rootPath = join(source, "keys-manifest.json");
  if (!existsSync(rootPath)) {
    if (check) return null;
    fail(`no catalogue at ${rootPath} (set KEYS_FIREFLY_DIR)`);
  }
  const root = readJson(rootPath);
  const profiles = field(root, "profiles");
  if (!Array.isArray(profiles) || profiles.length === 0) {
    fail("catalogue has no profiles");
  }

  const plan: Item[] = [];
  const seen = new Set<string>();
  const sums = new Map<string, string>();
  for (const profile of profiles as unknown[]) {
    const id = field(profile, "id");
    if (typeof id !== "string" || !ID.test(id) || id === "off") {
      fail(`bad profile id ${JSON.stringify(id)}`);
    }
    if (seen.has(id)) fail(`duplicate profile id ${id}`);
    seen.add(id);
    // Paths stay relative, inside the set's own folder: no "..", no absolute path.
    if (
      field(profile, "manifest") !== `${id}/keys-manifest.json` ||
      field(profile, "preview") !== `${id}/${PREVIEW}`
    ) {
      fail(`${id}: expected ${id}/keys-manifest.json and ${id}/${PREVIEW}`);
    }
    const folder = join(source, id);
    let name = text(field(profile, "name")) ?? id;
    let family = text(field(profile, "family"));
    let licence = DEFAULT_LICENCE;
    let files = LEGACY_FILES;
    const own = join(folder, "keys-manifest.json");
    if (existsSync(own)) {
      const full = readJson(own);
      if (field(full, "id") !== undefined && field(full, "id") !== id) {
        fail(
          `${id}: its keys-manifest.json is for ${String(field(full, "id"))}`,
        );
      }
      const preview = field(full, "preview");
      if (preview !== undefined && preview !== PREVIEW) {
        fail(`${id}: expected preview ${PREVIEW}`);
      }
      name = text(field(full, "name")) ?? name;
      family = family ?? text(field(full, "family"));
      licence = text(field(full, "licence")) ?? licence;
      files = samples(id, full);
    }
    for (const file of [...files, PREVIEW]) {
      const from = join(folder, file);
      if (!existsSync(from)) fail(`${id}: missing ${file}`);
      const hash = sha(from);
      sums.set(`${id}/${file}`, hash);
      plan.push({ from, sha: hash, to: join(dest, id, file), text: null });
    }
    // The full manifest (metrics, C2PA) stays in the Audio Lab; the game needs the file names.
    const slim = {
      id,
      name,
      ...(family === null ? {} : { family }),
      licence,
      files,
      preview: PREVIEW,
    };
    plan.push({
      from: null,
      sha: null,
      to: join(dest, id, "keys-manifest.json"),
      text: `${JSON.stringify(slim, null, 2)}\n`,
    });
  }
  plan.push(
    {
      from: null,
      sha: null,
      to: join(dest, "keys-manifest.json"),
      text: `${JSON.stringify(root, null, 2)}\n`,
    },
    { from: null, sha: null, to: join(dest, SUMS), text: sumsText(sums) },
    // Last: written only once every file above is in place.
    {
      from: null,
      sha: null,
      to: join(dest, "installed.json"),
      text: `${JSON.stringify({ sets: [...seen] }, null, 2)}\n`,
    },
  );
  return { plan, sets: [...seen], sums };
}

function current(item: Item): boolean {
  if (!existsSync(item.to)) return false;
  if (item.sha !== null) return sha(item.to) === item.sha;
  return readFileSync(item.to, "utf8") === item.text;
}

const rel = (path: string): string => path.slice(dest.length + 1);

/** Problems --check reports: the local audio against keys.sha256, then the Audio Lab against Git. */
function problems(lab: Lab | null): string[] {
  const found: string[] = [];
  const recorded = readSums();
  if (recorded === null) {
    found.push(`missing: ${SUMS} (run pnpm sync-keys)`);
  } else {
    for (const [path, hash] of recorded) {
      const local = join(dest, path);
      if (!existsSync(local)) {
        found.push(`missing: ${path}`);
      } else if (sha(local) !== hash) {
        found.push(`stale: ${path} is not the version ${SUMS} records`);
      }
    }
  }
  if (lab === null) return found;
  for (const item of lab.plan) {
    if (item.sha !== null || item.to === join(dest, SUMS)) continue;
    if (!current(item)) {
      found.push(
        `${existsSync(item.to) ? "stale" : "missing"}: ${rel(item.to)} (differs from the Audio Lab)`,
      );
    }
  }
  if (recorded !== null) {
    const paths = new Set([...recorded.keys(), ...lab.sums.keys()]);
    for (const path of [...paths].sort()) {
      if (recorded.get(path) !== lab.sums.get(path)) {
        found.push(`Audio Lab differs from ${SUMS}: ${path}`);
      }
    }
  }
  return found;
}

const lab = readLab();

if (check) {
  const found = problems(lab);
  if (lab === null) {
    console.log(
      `sync-keys: no Audio Lab at ${source}; local audio checked against ${SUMS} only`,
    );
  }
  if (found.length === 0) {
    const count = readSums()?.size ?? 0;
    console.log(`sync-keys: ${count} OGG files match ${SUMS} in ${dest}`);
    process.exit(0);
  }
  for (const line of found) console.log(line);
  console.log(
    `sync-keys: ${found.length} problem(s); run pnpm sync-keys, and commit ${SUMS} when the Audio Lab changed`,
  );
  process.exit(1);
}

if (lab === null) fail(`no catalogue at ${source}`);
const sumsPath = join(dest, SUMS);
const before = existsSync(sumsPath) ? readFileSync(sumsPath, "utf8") : null;
const stale = lab.plan.filter((item) => !current(item));
for (const item of stale) {
  mkdirSync(dirname(item.to), { recursive: true });
  if (item.from !== null) copyFileSync(item.from, item.to);
  else writeFileSync(item.to, item.text ?? "");
}
console.log(
  `sync-keys: ${lab.sets.length} sets from ${source}; ${stale.length} file(s) written, ${lab.plan.length - stale.length} unchanged`,
);
if (before !== sumsText(lab.sums)) {
  console.log(
    `sync-keys: ${SUMS} ${before === null ? "written" : "changed"}; commit it with the code that expects these sounds`,
  );
}
